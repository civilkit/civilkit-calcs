// "Do not ask again" on the Run Python question: node e2e/python-consent-check.mjs [--url http://127.0.0.1:4180/]
import { chromium } from 'playwright';
const i = process.argv.indexOf('--url');
const url = i > 0 ? process.argv[i + 1] : 'http://127.0.0.1:4180/';
const src = '#python\nprint("hello from python")\n#end python\n';
let fails = 0;
const ok = (c, m) => { console.log((c ? 'ok   ' : 'FAIL ') + m); if (!c) fails++; };
const exe = process.env.PW_EXECUTABLE;
const browser = await chromium.launch(exe ? { executablePath: exe } : {});
const ctx = await browser.newContext();
const open = async () => {
    const page = await ctx.newPage();
    await page.goto(url);
    await page.waitForFunction(() => window.calcpadActiveEditor != null, null, { timeout: 90000 });
    await page.evaluate((v) => window.calcpadActiveEditor.setValue(v), src);
    return page;
};
let page = await open();
await page.locator('#cprs-python-yes').waitFor({ timeout: 30000 });
ok(await page.locator('#cprs-python-never').isVisible(), 'the question has a Do not ask again box');
await page.locator('#cprs-python-never').check();
await page.locator('#cprs-python-yes').click();
ok((await page.evaluate(() => localStorage.getItem('cprs.python.alwaysRun'))) === '1', 'the choice is stored');
await page.close();
page = await open();
await page.waitForTimeout(6000);
ok((await page.locator('#cprs-python-consent').count()) === 0, 'a new tab does not ask');
await page.close();
await ctx.clearCookies();
const p2 = await ctx.newPage();
await p2.goto(url);
await p2.evaluate(() => localStorage.removeItem('cprs.python.alwaysRun'));
await p2.close();
page = await open();
ok(await page.locator('#cprs-python-yes').waitFor({ timeout: 30000 }).then(() => true, () => false), 'after the reset it asks again');
await page.locator('#cprs-python-no').click();
await browser.close();
console.log(fails ? fails + ' FAIL' : 'python consent check passed');
process.exit(fails ? 1 : 0);
